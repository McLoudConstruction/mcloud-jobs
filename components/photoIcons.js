// Line icons for the photo screens (no emoji anywhere). 24px grid, drawn
// with currentColor so they follow the surrounding text color.
function Svg({ size = 22, children, strokeWidth = 2, ...rest }) {
  return (
    <svg
      width={size} height={size} viewBox="0 0 24 24" fill="none"
      stroke="currentColor" strokeWidth={strokeWidth} strokeLinecap="round" strokeLinejoin="round"
      aria-hidden="true" focusable="false" {...rest}
    >
      {children}
    </svg>
  );
}

